/**
 * Renders every generated artifact of @esphelm/schema in memory, keyed by path relative to the
 * package root. `generate.ts` writes them; `test/generated.test.ts` checks they are up to date.
 */
import { readFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

interface UnitJson {
  label: string;
  factor: number;
  offset?: number;
  wrap?: [number, number];
}
interface UnitsFile {
  version: number;
  quantities: Record<string, { signalk: string; si: string; units: Record<string, UnitJson> }>;
}
interface CasesFile {
  cases: { si: number; unit: string; expected: number }[];
}

const GENERATED_NOTE =
  'GENERATED by packages/schema/scripts/generate.ts. Do not edit; run `npm run generate`.';
const LABEL_RE = /^[\x20-\x7E°]*$/;
const ID_RE = /^[A-Za-z][A-Za-z0-9]*$/;

interface FlatUnit {
  id: string;
  quantity: string;
  label: string;
  factor: number;
  offset: number;
  wrap: [number, number] | null;
}

function readJson<T>(rel: string): T {
  return JSON.parse(readFileSync(join(PACKAGE_ROOT, rel), 'utf8')) as T;
}

/** Flatten and sanity-check units.json; throws on any inconsistency. */
export function loadUnits(): { units: FlatUnit[]; quantities: UnitsFile['quantities'] } {
  const file = readJson<UnitsFile>('units.json');
  const units: FlatUnit[] = [];
  const seen = new Set<string>();
  const signalkSeen = new Set<string>();
  for (const [quantity, q] of Object.entries(file.quantities)) {
    if (!(q.si in q.units)) throw new Error(`units.json: SI unit "${q.si}" missing in ${quantity}`);
    if (typeof q.signalk !== 'string' || signalkSeen.has(q.signalk))
      throw new Error(`units.json: missing or duplicate SignalK units for ${quantity}`);
    signalkSeen.add(q.signalk);
    for (const [id, u] of Object.entries(q.units)) {
      if (!ID_RE.test(id))
        throw new Error(`units.json: unit id "${id}" must be an ASCII identifier`);
      if (seen.has(id)) throw new Error(`units.json: duplicate unit id "${id}"`);
      if (!LABEL_RE.test(u.label))
        throw new Error(`units.json: label of "${id}" outside ASCII + °`);
      if (!Number.isFinite(u.factor) || u.factor === 0)
        throw new Error(`units.json: bad factor for "${id}"`);
      if (u.wrap && !(u.wrap[0] < u.wrap[1])) throw new Error(`units.json: bad wrap for "${id}"`);
      seen.add(id);
      units.push({
        id,
        quantity,
        label: u.label,
        factor: u.factor,
        offset: u.offset ?? 0,
        wrap: u.wrap ?? null,
      });
    }
  }
  return { units, quantities: file.quantities };
}

/** Shortest round-trip decimal; always a valid double literal in C++. */
function cppDouble(n: number): string {
  const s = String(n);
  return /[.eE]/.test(s) ? s : `${s}.0`;
}

function cppString(s: string): string {
  // Escape the degree sign as UTF-8 bytes so the header is pure ASCII.
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/°/g, '\\xC2\\xB0" "')}"`;
}

function renderUnitsTs(units: FlatUnit[], quantities: UnitsFile['quantities']): string {
  const lines = [
    `// ${GENERATED_NOTE}`,
    '',
    `export const UNIT_IDS = [${units.map((u) => `'${u.id}'`).join(', ')}] as const;`,
    'export type UnitId = (typeof UNIT_IDS)[number];',
    '',
    'export interface UnitDef {',
    '  quantity: string;',
    '  label: string;',
    '  factor: number;',
    '  offset: number;',
    '  wrap: readonly [number, number] | null;',
    '}',
    '',
    'export const UNITS: Readonly<Record<UnitId, UnitDef>> = {',
    ...units.map(
      (u) =>
        `  ${u.id}: { quantity: '${u.quantity}', label: ${JSON.stringify(u.label)}, factor: ${u.factor}, offset: ${u.offset}, wrap: ${u.wrap ? `[${u.wrap[0]}, ${u.wrap[1]}]` : 'null'} },`,
    ),
    '};',
    '',
    'export const QUANTITIES: Readonly<',
    '  Record<string, { signalk: string; si: UnitId; units: readonly UnitId[] }>',
    '> = {',
    ...Object.entries(quantities).map(
      ([name, q]) =>
        `  ${name}: { signalk: '${q.signalk}', si: '${q.si}', units: [${Object.keys(q.units)
          .map((id) => `'${id}'`)
          .join(', ')}] },`,
    ),
    '};',
    '',
  ];
  return lines.join('\n');
}

function renderUnitsHeader(units: FlatUnit[]): string {
  return [
    `// ${GENERATED_NOTE}`,
    '// Display unit table shared with the TS schema package (units.json).',
    '#pragma once',
    '',
    '#include <cmath>',
    '#include <cstddef>',
    '#include <cstring>',
    '',
    'namespace esphelm {',
    'namespace units {',
    '',
    'struct UnitDef {',
    '  const char *id;',
    '  const char *quantity;',
    '  const char *label;  // UTF-8, ASCII + degree sign',
    '  double factor;',
    '  double offset;',
    '  bool has_wrap;',
    '  double wrap_min;',
    '  double wrap_max;',
    '};',
    '',
    '// Values within this fraction of the wrap span below wrap_max snap to wrap_min.',
    'constexpr double WRAP_EPSILON = 1e-9;',
    '',
    'inline constexpr UnitDef UNIT_TABLE[] = {',
    ...units.map(
      (u) =>
        `    {"${u.id}", "${u.quantity}", ${cppString(u.label)}, ${cppDouble(u.factor)}, ${cppDouble(u.offset)}, ${u.wrap ? 'true' : 'false'}, ${cppDouble(u.wrap?.[0] ?? 0)}, ${cppDouble(u.wrap?.[1] ?? 0)}},`,
    ),
    '};',
    `inline constexpr size_t UNIT_COUNT = ${units.length};`,
    '',
    '/// Look up a unit by id; nullptr if unknown.',
    'inline const UnitDef *find_unit(const char *id) {',
    '  for (const auto &u : UNIT_TABLE) {',
    '    if (std::strcmp(u.id, id) == 0)',
    '      return &u;',
    '  }',
    '  return nullptr;',
    '}',
    '',
    '/// SI value to display value: si * factor + offset, wrapped into [wrap_min, wrap_max).',
    'inline double to_display(double si, const UnitDef &u) {',
    '  double v = si * u.factor + u.offset;',
    '  if (u.has_wrap) {',
    '    const double span = u.wrap_max - u.wrap_min;',
    '    v = v - span * std::floor((v - u.wrap_min) / span);',
    '    if (u.wrap_max - v < WRAP_EPSILON * span)',
    '      v = u.wrap_min;',
    '  }',
    '  return v;',
    '}',
    '',
    '/// Display value back to SI (no wrapping), e.g. for PUT requests.',
    'inline double from_display(double display, const UnitDef &u) { return (display - u.offset) / u.factor; }',
    '',
    '}  // namespace units',
    '}  // namespace esphelm',
    '',
  ].join('\n');
}

function renderCasesHeader(cases: CasesFile['cases']): string {
  return [
    `// ${GENERATED_NOTE}`,
    '// Shared conversion cases from fixtures/units.cases.json.',
    '#pragma once',
    '',
    'namespace esphelm {',
    'namespace units {',
    '',
    'struct UnitCase {',
    '  double si;',
    '  const char *unit;',
    '  double expected;',
    '};',
    '',
    'inline constexpr UnitCase UNIT_CASES[] = {',
    ...cases.map((c) => `    {${cppDouble(c.si)}, "${c.unit}", ${cppDouble(c.expected)}},`),
    '};',
    '',
    '}  // namespace units',
    '}  // namespace esphelm',
    '',
  ].join('\n');
}

/** Starter layouts (templates/*.json) as a typed module for the editor. */
function renderTemplatesTs(): string {
  const dir = join(PACKAGE_ROOT, 'templates');
  const order = ['wind', 'grid', 'energy', 'engine', 'switchboard'];
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.slice(0, -'.json'.length))
    .sort(
      (a, b) => (order.indexOf(a) + 1 || 99) - (order.indexOf(b) + 1 || 99) || a.localeCompare(b),
    );
  const entries = files.map(
    (name) =>
      `  ${JSON.stringify(name)}: ${JSON.stringify(readJson<unknown>(`templates/${name}.json`))},`,
  );
  return [
    `// ${GENERATED_NOTE}`,
    "import type { Layout } from '../layout.js';",
    '',
    '/** Starter layouts porting the legacy static apps (packages/schema/templates). */',
    'export const TEMPLATES: Readonly<Record<string, Layout>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

function renderJsonSchema(schema: object): string {
  return `${JSON.stringify(schema, null, 2)}\n`;
}

export const UNITS_TS = 'src/generated/units.ts';

/** The TS units table alone; the schema modules import it, so it must exist before renderAll(). */
export function renderUnitsTsFile(): string {
  const { units, quantities } = loadUnits();
  return renderUnitsTs(units, quantities);
}

export async function renderAll(): Promise<Record<string, string>> {
  const { units, quantities } = loadUnits();
  const { cases } = readJson<CasesFile>('fixtures/units.cases.json');
  // Imported lazily: these modules depend on the generated units table.
  const { Layout } = await import('../src/layout.js');
  const { Hello } = await import('../src/hello.js');
  return {
    [UNITS_TS]: renderUnitsTs(units, quantities),
    'src/generated/templates.ts': renderTemplatesTs(),
    'generated/esphelm_units.h': renderUnitsHeader(units),
    // Firmware copy of the same header (the ESPHome component cannot reach packages/).
    '../../firmware/components/esphelm_runtime/esphelm_units.h': renderUnitsHeader(units),
    'generated/units_cases.h': renderCasesHeader(cases),
    'schema/layout.schema.json': renderJsonSchema(Layout),
    'schema/hello.schema.json': renderJsonSchema(Hello),
  };
}
